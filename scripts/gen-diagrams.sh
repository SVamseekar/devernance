#!/usr/bin/env bash
# Regenerate code-derived diagrams into docs/diagrams/generated/.
#
# Every diagram here is produced by a tool reading the source, migrations,
# Compose files, Terraform or workflow YAML, so re-running this script after a
# change keeps them in sync. Writes docs/diagrams/README.md as the index.
#
# Requires: python3, uv, node/npx, Graphviz (`brew install graphviz`).
# Docker is required only for --db and --terraform.
#
# Usage:
#   scripts/gen-diagrams.sh                 # compose, dashboard, pipelines
#   scripts/gen-diagrams.sh --db            # + ER diagram (throwaway Postgres + Flyway + SchemaSpy)
#   scripts/gen-diagrams.sh --terraform     # + Terraform module graph
#   scripts/gen-diagrams.sh --java          # + API package graph (mvn compile + jdeps)
#   scripts/gen-diagrams.sh --all
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/docs/diagrams/generated"
INDEX="$ROOT/docs/diagrams/README.md"

WITH_DB=false WITH_TF=false WITH_JAVA=false
for arg in "$@"; do
  case "$arg" in
    --db) WITH_DB=true ;;
    --terraform) WITH_TF=true ;;
    --java) WITH_JAVA=true ;;
    --all) WITH_DB=true WITH_TF=true WITH_JAVA=true ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

mkdir -p "$OUT"
cd "$ROOT"

echo "==> Compose topology (docker compose config)"
docker compose -f infra/docker-compose.yml --env-file .env.example --profile full \
  config --format json | python3 scripts/compose_to_mermaid.py > "$OUT/compose.mmd"
docker compose -f infra/docker-compose.yml -f infra/docker-compose.dell.yml \
  --env-file .env.dell.example --profile full \
  config --format json | python3 scripts/compose_to_mermaid.py > "$OUT/compose-dell.mmd"
docker compose -f infra/docker-compose.prod.yml --env-file infra/.env.prod.example \
  config --format json | python3 scripts/compose_to_mermaid.py > "$OUT/compose-prod.mmd"

echo "==> Dashboard module areas (madge)"
(cd apps/dashboard && npx -y madge --extensions ts,tsx --ts-config tsconfig.json --json \
  app components lib hooks context middleware.ts 2>/dev/null) \
  | python3 scripts/imports_to_mermaid.py > "$OUT/dashboard-imports.mmd"

echo "==> CI/CD pipelines (workflow YAML)"
uvx --quiet --with pyyaml python scripts/workflow_to_mermaid.py \
  .github/workflows/*.yml > "$OUT/pipelines.md"

if $WITH_TF; then
  echo "==> Terraform module graph"
  TF=(docker run --rm -v "$ROOT":/work -w /work/infra/terraform hashicorp/terraform:1.9)
  "${TF[@]}" init -backend=false -input=false >/dev/null
  "${TF[@]}" graph > "$OUT/terraform.dot"
  dot -Tsvg "$OUT/terraform.dot" -o "$OUT/terraform.svg"
fi

if $WITH_DB; then
  echo "==> ER diagram (throwaway Postgres, Flyway migrations, SchemaSpy)"
  NET="eu-ai-assurance-diagrams"
  PG="$NET-pg"
  SCHEMA_TMP="$(mktemp -d)"
  chmod 777 "$SCHEMA_TMP"
  cleanup() {
    docker stop "$PG" >/dev/null 2>&1 || true
    docker network rm "$NET" >/dev/null 2>&1 || true
  }
  trap cleanup EXIT
  docker network create "$NET" >/dev/null
  docker run -d --rm --name "$PG" --network "$NET" \
    -e POSTGRES_DB=er -e POSTGRES_USER=er -e POSTGRES_PASSWORD=er \
    pgvector/pgvector:pg16 >/dev/null
  until docker exec "$PG" pg_isready -U er -d er >/dev/null 2>&1; do sleep 2; done
  docker run --rm --network "$NET" \
    -v "$ROOT/services/api/src/main/resources/db":/db:ro flyway/flyway:10 \
    -url="jdbc:postgresql://$PG:5432/er" -user=er -password=er \
    -locations=filesystem:/db/migration,filesystem:/db/postgresql migrate >/dev/null
  docker run --rm --network "$NET" -v "$SCHEMA_TMP":/output schemaspy/schemaspy:6.2.4 \
    -t pgsql11 -host "$PG" -port 5432 -db er -u er -p er -s public -norows >/dev/null
  cp "$SCHEMA_TMP/diagrams/summary/relationships.real.large.png" "$OUT/er-diagram.png"
  cp "$SCHEMA_TMP/diagrams/summary/relationships.real.compact.png" "$OUT/er-diagram-compact.png"
  echo "    Full browsable schema site: $SCHEMA_TMP/index.html"
fi

if $WITH_JAVA; then
  echo "==> API package graph (jdeps)"
  mvn -q -f services/api/pom.xml compile -DskipTests
  JDEPS_TMP="$(mktemp -d)"
  jdeps -verbose:package -include 'os\..*' -e 'os\..*' -dotoutput "$JDEPS_TMP" \
    services/api/target/classes
  dot -Tsvg "$JDEPS_TMP/classes.dot" -o "$OUT/api-packages.svg"
fi

echo "==> Index ($INDEX)"
embed() {
  echo '```mermaid'
  cat "$1"
  echo '```'
  echo
}
section_img() { # title, file, caption
  if [ -f "$OUT/$2" ]; then
    echo "## $1"
    echo
    echo "$3"
    echo
    echo "![$1](generated/$2)"
    echo
  fi
}
{
  echo "# Diagrams"
  echo
  echo "Generated by \`scripts/gen-diagrams.sh\` from source, migrations, Compose,"
  echo "Terraform and workflow files. Do not edit by hand; re-run the script."
  echo
  echo "## Production topology (infra/docker-compose.prod.yml)"
  echo
  embed "$OUT/compose-prod.mmd"
  echo "## Local runtime topology (Docker Compose, all profiles)"
  echo
  embed "$OUT/compose.mmd"
  echo "## Runtime topology (Dell lab overlay)"
  echo
  embed "$OUT/compose-dell.mmd"
  echo "## Dashboard module areas"
  echo
  echo "Imports between dashboard folders; edge labels count import statements."
  echo
  embed "$OUT/dashboard-imports.mmd"
  echo "## CI/CD pipelines"
  echo
  cat "$OUT/pipelines.md"
  section_img "Database schema (ER)" er-diagram-compact.png \
    "Tables and foreign keys after all Flyway migrations. Full columns: [er-diagram.png](generated/er-diagram.png)."
  section_img "Infrastructure (Terraform modules)" terraform.svg \
    "Module wiring of the Terraform skeleton (placeholder resources only)."
  section_img "API package dependencies" api-packages.svg \
    "Package-level dependencies inside the Spring Boot API (jdeps)."
} > "$INDEX"

# End each Markdown file with exactly one newline (pre-commit end-of-file-fixer).
for md in "$INDEX" "$OUT/pipelines.md"; do
  python3 -c 'import sys; p = sys.argv[1]; t = open(p).read().rstrip("\n") + "\n"; open(p, "w").write(t)' "$md"
done

echo "Done. Open $INDEX (Markdown preview) or view it on GitHub."
